#!/usr/bin/env bash
# Stop hook — keep Claude working while the change is not in a finishable state.
#
# Exit codes for this event:
#   0  let Claude stop.
#   2  prevent the stop. Claude receives stderr as the reason and continues.
#
# Loop protection: when Claude is already continuing because of a stop hook,
# the input has "stop_hook_active": true and this hook lets it stop. Claude
# Code also caps consecutive continuations.
#
# Default checks, on files changed since the last commit:
#   - unresolved merge-conflict markers
#   - unfilled tq-forge scaffold placeholders
# Add your own check in the marked place below (for example your test command).
#
# Generated by tq-forge.

set -uo pipefail

input="$(cat)"

already_continuing="$(printf '%s' "$input" | python3 -c '
import json, sys
try:
    print("yes" if json.load(sys.stdin).get("stop_hook_active") else "no")
except Exception:
    print("no")
' 2>/dev/null)"

[[ "$already_continuing" == "yes" ]] && exit 0

cd "${CLAUDE_PROJECT_DIR:-.}" 2>/dev/null || exit 0
git rev-parse --is-inside-work-tree >/dev/null 2>&1 || exit 0

problems=()

while IFS= read -r -d '' file; do
    [[ -f "$file" ]] || continue
    if grep -qE '^(<<<<<<<|>>>>>>>)( |$)' -- "$file" 2>/dev/null; then
        problems+=("unresolved merge-conflict markers in ${file}")
    fi
    if grep -qF 'TODO(tq-forge)' -- "$file" 2>/dev/null; then
        problems+=("unfilled TODO(tq-forge) placeholder in ${file}")
    fi
done < <(git diff --name-only -z HEAD 2>/dev/null; git ls-files --others --exclude-standard -z 2>/dev/null)

# --- Add your own check here. Example:
# if ! npm test --silent >/dev/null 2>&1; then
#     problems+=("npm test is failing")
# fi

if (( ${#problems[@]} > 0 )); then
    {
        printf 'Not finished yet (from .claude/hooks/stop.sh):\n'
        printf -- '- %s\n' "${problems[@]}"
        printf 'Fix these, or tell the user why they should stay.\n'
    } >&2
    exit 2
fi

exit 0
