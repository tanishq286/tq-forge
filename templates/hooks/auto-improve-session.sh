#!/usr/bin/env bash
# SessionStart / Stop hook — keep the Claude Code setup lean without being asked.
#
# It starts `tq-forge auto-improve --apply` in the background when either
#   - a `tq-forge sync-models` run recorded a new model since the last pass, or
#   - the always-loaded context is over the threshold (default 4,000 tokens).
#
# The context is measured at most once per interval (default one day), so most
# sessions pay only for a few file checks. The pass itself runs detached: this
# hook never waits for it, prints nothing (stdout from a SessionStart hook goes
# into Claude's context), and always exits 0 so it cannot block a session.
#
# Every change is backed up to <root>/.tq-forge-backup/ and logged to
# $TQ_FORGE_HOME/auto-improve.log. Undo with `tq-forge restore --root <root>`.
#
# Settings (environment):
#   TQ_FORGE_AUTO_IMPROVE=0        turn the hook off
#   TQ_FORGE_AUTO_ROOT             setup to improve          (default: $HOME)
#   TQ_FORGE_BLOAT_THRESHOLD       tokens that trigger a pass (default: 4000)
#   TQ_FORGE_AUTO_INTERVAL         seconds between measurements (default: 86400)
#   TQ_FORGE_AUTO_FLAGS            extra flags, e.g. "--follow-symlinks --dedupe-plugins"
#   TQ_FORGE_SCRIPTS               tq-forge scripts folder   (default: $TQ_FORGE_HOME/install/scripts)
#
# Generated by tq-forge. Edit freely.

set -uo pipefail

cat >/dev/null 2>&1 || true  # the hook input arrives as JSON on stdin; this hook does not need it

[[ "${TQ_FORGE_AUTO_IMPROVE:-1}" == "0" ]] && exit 0

state="${TQ_FORGE_HOME:-$HOME/.tq-forge}"
scripts="${TQ_FORGE_SCRIPTS:-$state/install/scripts}"
root="${TQ_FORGE_AUTO_ROOT:-$HOME}"
threshold="${TQ_FORGE_BLOAT_THRESHOLD:-4000}"
interval="${TQ_FORGE_AUTO_INTERVAL:-86400}"
stamp="$state/auto-improve.stamp"
synced="$state/model-sync.json"

[[ -f "$scripts/auto-improve.sh" && -f "$scripts/optimize.sh" ]] || exit 0
command -v python3 >/dev/null 2>&1 || exit 0
[[ "$threshold" =~ ^[0-9]+$ && "$interval" =~ ^[0-9]+$ ]] || exit 0

reason=""
if [[ -f "$synced" && ( ! -f "$stamp" || "$synced" -nt "$stamp" ) ]]; then
    reason="a new model was synced"
else
    now="$(date +%s)"
    last=0
    if [[ -f "$stamp" ]]; then
        last="$(python3 -c 'import os, sys; print(int(os.path.getmtime(sys.argv[1])))' "$stamp" 2>/dev/null || echo 0)"
    fi
    [[ "$last" =~ ^[0-9]+$ ]] || last=0
    (( now - last < interval )) && exit 0
    tokens="$(bash "$scripts/optimize.sh" measure --root "$root" 2>/dev/null \
        | python3 -c 'import json, sys; print(json.load(sys.stdin)["estimated_tokens"])' 2>/dev/null || echo 0)"
    [[ "$tokens" =~ ^[0-9]+$ ]] || tokens=0
    if (( tokens > threshold )); then
        reason="always-loaded context is ${tokens} tokens (over ${threshold})"
    fi
fi

mkdir -p "$state" 2>/dev/null || exit 0
touch "$stamp" 2>/dev/null || exit 0  # measured (or about to improve): wait one interval before the next look

[[ -z "$reason" ]] && exit 0

printf '%s auto-improve: %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$reason" >>"$state/auto-improve.log" 2>/dev/null

# shellcheck disable=SC2086  # TQ_FORGE_AUTO_FLAGS is a list of flags and is split on purpose
nohup bash "$scripts/auto-improve.sh" --root "$root" --apply ${TQ_FORGE_AUTO_FLAGS:-} \
    >>"$state/auto-improve.log" 2>&1 </dev/null &

exit 0
